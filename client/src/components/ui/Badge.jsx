const TONES = {
  slate: 'bg-slate-100 text-slate-700',
  blue: 'bg-blue-100 text-blue-800',
  green: 'bg-green-100 text-green-800',
  amber: 'bg-amber-100 text-amber-800',
  orange: 'bg-orange-100 text-orange-800',
  red: 'bg-red-100 text-red-800',
  purple: 'bg-purple-100 text-purple-800',
  ai: 'bg-violet-100 text-violet-800 ring-1 ring-violet-300',
};

export function Badge({ tone = 'slate', children, title }) {
  return (
    <span title={title} className={`inline-flex items-center rounded-full px-2 py-0.5 text-xs font-medium ${TONES[tone] ?? TONES.slate}`}>
      {children}
    </span>
  );
}

export function AiBadge({ children = 'AI-suggested' }) {
  return (
    <Badge tone="ai" title="Generated by a local model. A human decides what is true.">
      ✨ {children}
    </Badge>
  );
}
